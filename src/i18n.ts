const dict: Record<LocaleCode, Record<TranslationKey, string>> = { en, vi };

let currentLocale: LocaleCode = 'en';

export function setLocale(locale: LocaleCode) {
  currentLocale = locale;
}

export function getLocale(): LocaleCode {
  return currentLocale;
}

export function t(key: TranslationKey, locale?: LocaleCode): string {
  const l = locale ?? currentLocale;
  return dict[l]?.[key] ?? dict.en[key] ?? key;
}

export function createT(locale: LocaleCode) {
  return (key: TranslationKey) => t(key, locale);
}
